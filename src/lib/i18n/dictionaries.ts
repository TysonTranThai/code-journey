const DICTIONARIES: Record<Locale, Dictionary> = { en, vi };

export function getDictionary(locale: Locale): Dictionary {
  return DICTIONARIES[locale];
}

/** Select the plural form for `count` (Vietnamese has no plural distinction). */
export function pluralForm(locale: Locale, count: number, forms: Plural): string {
  return locale === "vi" ? forms.other : count === 1 ? forms.one : forms.other;
}
